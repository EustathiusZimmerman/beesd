const gdt = @import("gdt.zig");
const pic = @import("pic.zig");
const tty = @import("tty.zig");
const common = @import("common.zig");

/// Struct representation of the IDT
pub const IdtEntry = packed struct {
	base_low: u16,
	selector: u16,
	zero: u8,
	gate_type: u4,
	storage_segment: u1,
	privilege: u2,
	present: u1,
	base_high: u16,
};

/// Struct representation of the pointer to the IDT
pub const IdtPtr = packed struct {
	limit: u16,
	base: u32,
};

/// Struct representation of the interrupt frame
pub const InterruptFrame = extern struct {
	gs: u32,
	fs: u32,
	es: u32,
	ds: u32,
	edi: u32,
	esi: u32,
	ebp: u32,
	esp: u32,
	ebx: u32,
	edx: u32,
	ecx: u32,
	eax: u32,
	vector: u32,
	error_code: u32,
	eip: u32,
	cs: u32,
	eflags: u32,
};

pub const IRQ_BASE: u8 = 32;
pub const IRQ_COUNT: u8 = 16;

comptime {
	if(@sizeOf(IdtEntry) != 8) {
		@compileError("IdtEntry must be exactly 8 bytes");
	}
	if(@sizeOf(InterruptFrame) != 17 * @sizeOf(u32)) {
		@compileError("InterruptFrame does not match the assembly stack layout");
	}
}

pub const IrqHandler = *const fn (frame: *InterruptFrame) void;

const INTERRUPT_GATE: u4 = 0xE;

const NUMBER_OF_ENTRIES: usize = 256;

const TABLE_SIZE: u16 = @intCast(@sizeOf(IdtEntry) * NUMBER_OF_ENTRIES - 1);

/// Stub addresses generated by interrupts.S, one per IDT vector.
extern const isr_stub_table: [NUMBER_OF_ENTRIES]u32;

var idt_ptr: IdtPtr = IdtPtr{
	.limit = TABLE_SIZE,
	.base = 0,
};

/// All of the IDT Entries, all of the properties set to 0 initially
var idt_entries: [NUMBER_OF_ENTRIES]IdtEntry = @splat(.{
	.base_low = 0,
	.selector = 0,
	.zero = 0,
	.gate_type = 0,
	.storage_segment = 0,
	.privilege = 0,
	.present = 0,
	.base_high = 0,
});

var irq_handlers: [IRQ_COUNT]?IrqHandler = @splat(null);

/// Interrupt exception names
// Copied from https://en.wikipedia.org/wiki/Interrupt_descriptor_table
const exception_names: [32][]const u8 = .{
	"Divide Error",
	"Debug",
	"Non-Maskable Interrupt",
	"Breakpoint",
	"Overflow",
	"BOUND Range Exceeded",
	"Invalid Opcode (Undefined Opcode)",
	"Device Not Available",
	"Double Fault",
	"Coprocessor Segment Overrun",
	"Invalid TSS",
	"Segment Not Present",
	"Stack-Segment Fault",
	"General Protection Fault",
	"Page Fault",
	"Reserved",
	"x87 Floating-Point Exception",
	"Alignment Check",
	"Machine Check",
	"SIMD Floating-Point Exception",
	"Virtualization Exception",
	"Control Protection Exception",
	"Reserved",
	"Reserved",
