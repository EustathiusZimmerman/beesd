	"Reserved",
	"Hypervisor Injection Exception",
	"VMM Communication Exception",
	"Security Exception",
	"Reserved",
};

/// Sets an IDT entry
fn 
set_gate(vector: usize, handler: u32, selector: u16, gate_type: u4, privilege: u2) void 
{
	idt_entries[vector] = .{
		.base_low = @truncate(handler),
		.selector = selector,
		.zero = 0,
		.gate_type = gate_type,
		.storage_segment = 0,
		.privilege = privilege,
		.present = 1,
		.base_high = @truncate(handler >> 16),
	};
}

/// Registers an interrupt request
pub fn 
register_irq(irq: u8, handler: IrqHandler) void 
{
	if (irq >= IRQ_COUNT) return;
	irq_handlers[irq] = handler;
}

/// DeRegisters an interrupt request
pub fn 
unregister_irq(irq: u8) void 
{
	if (irq >= IRQ_COUNT) return;
	irq_handlers[irq] = null;
}

/// Gets the name of an interrupt exception
fn 
exception_name(vector: u32) []const u8 
{
	if (vector < exception_names.len) {
		return exception_names[@intCast(vector)];
	}
	return "Unknown";
}

/// Check whether the interrupt exception has its own error code or not
fn 
exception_has_error_code(vector: u32) bool 
{
	return switch (vector) {
		8, 10, 11, 12, 13, 14, 17, 21, 29, 30 => true,
		else => false,
	};
}

/// Handles the interrupt exception
fn 
handle_exception(frame: *InterruptFrame) void 
{
	tty.set_color(.light_red, .black);
	tty.print("\nException {}: {s}\n", .{ frame.vector, exception_name(frame.vector) });

	if(exception_has_error_code(frame.vector)) {
		tty.print("  error code: 0x{x}\n", .{frame.error_code});
	}

	tty.print("  EIP=0x{x} CS=0x{x} EFLAGS=0x{x}\n", .{
		frame.eip,
		frame.cs,
		frame.eflags,
	});
	tty.print("  EAX=0x{x} EBX=0x{x} ECX=0x{x} EDX=0x{x}\n", .{
		frame.eax,
		frame.ebx,
		frame.ecx,
		frame.edx,
	});
	tty.print("  ESI=0x{x} EDI=0x{x} EBP=0x{x} ESP=0x{x}\n", .{
		frame.esi,
		frame.edi,
		frame.ebp,
		frame.esp,
	});
	tty.set_color(.white, .black);

	// A breakpoint is recoverable: return to the instruction after int3.
	if(frame.vector == 3) {
		return;
	}

	common.disable_interrupts();
	while(true) {
		common.halt_cpu();
	}
}

/// Handles a CPU interrupt request
fn 
handle_irq(frame: *InterruptFrame) void 
{
	const irq: u8 = @intCast(frame.vector - IRQ_BASE);

	if(irq < IRQ_COUNT) {
		if(irq_handlers[irq]) |handler| {
			handler(frame);
		}
	}

	pic.send_eoi(irq);
}

export fn 
interrupt_handler(frame: *InterruptFrame) callconv(.c) void 
{
	if (frame.vector < 32) {
		handle_exception(frame);
		return;
	}

	if (frame.vector >= IRQ_BASE and frame.vector < IRQ_BASE + IRQ_COUNT) {
		handle_irq(frame);
		return;
	}

	tty.print("Unhandled interrupt {}\n", .{frame.vector});
}

/// Initializes the Interrupt Descriptor Table
pub fn 
init() void 
{
	tty.print("Loading IDT... ", .{});
	defer tty.print("Done\n", .{});

	for(0..NUMBER_OF_ENTRIES) |vector| {
		set_gate(vector, isr_stub_table[vector], gdt.KERNEL_CODE_OFFSET, INTERRUPT_GATE, 0);
	}

	idt_ptr.base = @intFromPtr(&idt_entries);

	common.lidt(&idt_ptr);
}
